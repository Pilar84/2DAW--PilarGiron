/*¿Dónde está el "document" en la jerarquía? 
Esta en la raiz del DOM y representa el documento HTML completo.


¿A qué clase pertenece el document? 
Es un objeto de la clase Document.

¿Cuál es su lugar en la jerarquía DOM? 
Esta por encima del html. Es el nodo raiz y en él se encuentran todos los demás nodos del documento(html, head, body, etc).

¿Hereda de Node o Element, o tal vez HTMLElement?
Hereda de node porque es el nodo raiz del DOM y no es un elemento HTML específico, sino que representa el documento completo.*/
